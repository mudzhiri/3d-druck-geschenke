type Key = keyof typeof baseKeys;

const dictionaries = Object.fromEntries(
  (["de", "en", "fr", "es", "it", "zh"] as Locale[]).map((locale) => [
    locale,
    Object.fromEntries(
      (Object.keys(baseKeys) as Key[]).map((key) => [
        key,
        pickLocalized(baseKeys[key], locale),
      ]),
    ),
  ]),
) as Record<Locale, Dict>;

export function t(locale: Locale, key: string, vars?: Record<string, string | number>) {
  const table = dictionaries[locale] ?? dictionaries.de;
  let value = table[key] ?? dictionaries.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      value = value.replace(`{${k}}`, String(v));
    }
  }
  return value;
}
